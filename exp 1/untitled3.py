plt.contourf(xx, yy, Z_numeric, cmap=plt.cm.RdYlBu, alpha=0.6)

# Plot the data points
scatter = plt.scatter(X_2d[:, 0], X_2d[:, 1], c=y_numeric, cmap=plt.cm.RdYlBu, edgecolor='k', s=20)
