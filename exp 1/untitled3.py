plt.ylabel(X_encoded.columns[previous_grade_idx] + ' (Scaled)')
plt.title('Logistic Regression Decision Boundaries with Final Exam Score and Previous Grade')

# Create a legend with original labels
handles, _ = scatter.legend_elements()
legend_labels = [label for label, i in sorted(label_mapping.items(), key=lambda item: item[1])]
plt.legend(handles=handles, labels=legend_labels, title='Final Grade')

# Add colorbar with correct ticks and labels
cbar = plt.colorbar(scatter, ticks=np.unique(y_numeric))
cbar.set_ticklabels(legend_labels)

plt.grid(True)
