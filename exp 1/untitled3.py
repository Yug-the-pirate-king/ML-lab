# Define features (X) and target (y)
X = df.drop(['student_id', 'final_grade'], axis=1)
y = df['final_grade']

print(f"Features shape: {X.shape}")
print(f"Target shape: {y.shape}")

# Identify categorical columns for one-hot encoding
categorical_cols = X.select_dtypes(include=['object']).columns

# Apply one-hot encoding
X_encoded = pd.get_dummies(X, columns=categorical_cols, drop_first=True)

display(X_encoded.head())

from sklearn.model_selection import train_test_split
from sklearn.preprocessing import StandardScaler

# Split the data into training and testing sets
X_train, X_test, y_train, y_test = train_test_split(X_encoded, y, test_size=0.3, random_state=42, stratify=y)

# Initialize StandardScaler
scaler = StandardScaler()

# Fit on training data and transform both training and testing data
X_train_scaled = scaler.fit_transform(X_train)
X_test_scaled = scaler.transform(X_test)

# For cross-validation, scale the entire X_encoded dataset (or apply scaler within CV pipeline)
X_encoded_scaled = scaler.fit_transform(X_encoded.copy())

print(f"X_train scaled shape: {X_train_scaled.shape}")
print(f"X_test scaled shape: {X_test_scaled.shape}")
print(f"y_train shape: {y_train.shape}")
print(f"y_test shape: {y_test.shape}")

# Check the distribution of the target variable in train and test sets
print('\nTarget distribution in training set:')
display(y_train.value_counts(normalize=True))
print('\nTarget distribution in test set:')
display(y_test.value_counts(normalize=True))

from sklearn.model_selection import KFold

# Set up K-Fold Cross-Validation
n_splits = 5
kf = KFold(n_splits=n_splits, shuffle=True, random_state=42)

print(f"K-Fold Cross-Validation set up with {n_splits} splits.")
print(f"Number of splits: {kf.get_n_splits(X_encoded)}")

from sklearn.linear_model import LogisticRegression
from sklearn.metrics import accuracy_score, precision_score, recall_score, f1_score

# Initialize and train the Logistic Regression model
# We increase max_iter to ensure convergence for complex datasets
model = LogisticRegression(max_iter=1000, random_state=42)
# Use scaled training data
model.fit(X_train_scaled, y_train)

# Make predictions on the scaled test set
y_pred = model.predict(X_test_scaled)

# Evaluate the model
accuracy = accuracy_score(y_test, y_pred)
precision = precision_score(y_test, y_pred, average='weighted', zero_division=0)
recall = recall_score(y_test, y_pred, average='weighted', zero_division=0)
f1 = f1_score(y_test, y_pred, average='weighted', zero_division=0)

print(f"Model: Logistic Regression")
print(f"Accuracy: {accuracy:.4f}")
print(f"Precision (weighted): {precision:.4f}")
print(f"Recall (weighted): {recall:.4f}")
print(f"F1-Score (weighted): {f1:.4f}")

"""### K-Fold Cross-Validation for Logistic Regression

Now, we'll apply the K-Fold Cross-Validation strategy to our Logistic Regression model to get more robust performance metrics.
"""

from sklearn.model_selection import cross_validate

# Perform cross-validation using the scaled entire dataset
cv_results = cross_validate(
    model, X_encoded_scaled, y,
    cv=kf,
    scoring=['accuracy', 'precision_weighted', 'recall_weighted', 'f1_weighted'],
    return_train_score=False # We are interested in test scores
)

print("K-Fold Cross-Validation Results for Logistic Regression (with scaled data):")
print(f"Average Accuracy: {cv_results['test_accuracy'].mean():.4f}")
print(f"Average Precision (weighted): {cv_results['test_precision_weighted'].mean():.4f}")
print(f"Average Recall (weighted): {cv_results['test_recall_weighted'].mean():.4f}")
print(f"Average F1-Score (weighted): {cv_results['test_f1_weighted'].mean():.4f}")

print("\nAll CV scores:")
for metric in cv_results:
    print(f"{metric}: {cv_results[metric]}")

